STATUSES = {"SYNTHETIC_ONLY_HOLD", "SYNTHETIC_ONLY_COMPLETE"}
SAMPLE_WEEK = "2099-06-12"
SAMPLE_PREVIOUS = "2099-06-05"
SAMPLE_BLOCKER = f"{SAMPLE_WEEK}:fed_h10_nominal_broad:MISSING_SYNTHETIC_RECEIPT"


