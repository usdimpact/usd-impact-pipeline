def assert_schema_stays_closed(schema: dict) -> None:
    """Pin authority and structural parity; not a full JSON Schema interpreter."""
    if schema.get("$schema") != "https://json-schema.org/draft/2020-12/schema":
        raise ValueError("unreviewed JSON Schema dialect")
    if schema.get("$id") != "urn:usd-impact:internal:independent-macro-context-synthetic-preview-v0":
        raise ValueError("schema cannot identify a public endpoint or new contract")
    if schema.get("type") != "object" or schema.get("additionalProperties") is not False:
        raise ValueError("preview root must remain closed")
    properties = schema.get("properties", {})
    model_keys = {field.name for field in fields(SyntheticContextPanel)}
    if set(properties) != model_keys or set(schema.get("required", [])) != model_keys:
        raise ValueError("wire fields diverged from invented Python preview")
    if properties["panel_id"].get("const") != PANEL_ID:
        raise ValueError("synthetic panel identity changed")
    if properties["fixture_marker"].get("const") != SYNTHETIC_MARKER:
        raise ValueError("synthetic-only fixture marker changed")
    if set(properties["status"].get("enum", [])) != STATUSES:
        raise ValueError("synthetic-only states changed")
    for key in AUTH_FIELDS:
        if properties[key] != {"type": "boolean", "const": False}:
            raise ValueError("release or source-rights flag may never be enabled")

    date_exprs = []
    for key in ("reference_week", "previous_week"):
        info = properties[key]
        if info.get("type") != "string":
            raise ValueError("invented date is not a string")
        pattern = info.get("pattern", "")
        date_exprs.append(pattern)
        if not pattern.startswith("^") or not pattern.endswith("$"):
            raise ValueError("synthetic date guard is unanchored")
        if not re.fullmatch(pattern, SAMPLE_WEEK) or not re.fullmatch(pattern, SAMPLE_PREVIOUS):
            raise ValueError("synthetic Friday fixture excluded")
        if re.fullmatch(pattern, "2026-10-30") or re.fullmatch(pattern, "2098-12-26"):
            raise ValueError("real/historical date accepted")
    if date_exprs[0] != date_exprs[1]:
        raise ValueError("two period date families diverge")

    dial_schema = properties["dial_labels"]
    if (dial_schema.get("type") != "array" or dial_schema.get("minItems") != 0
            or dial_schema.get("maxItems") != len(DIALS)
            or dial_schema.get("items") is not False
            or len(dial_schema.get("prefixItems", [])) != len(DIALS)):
        raise ValueError("four-label sequence is not closed")
    for expected_name, slot in zip(DIALS, dial_schema["prefixItems"], strict=True):
        if (slot.get("type") != "array" or slot.get("minItems") != 2
                or slot.get("maxItems") != 2 or slot.get("items") is not False):
            raise ValueError("qualitative pair has unreviewed extra elements")
        items = slot.get("prefixItems")
        if (not isinstance(items, list) or len(items) != 2
                or items[0] != {"type": "string", "const": expected_name}
                or items[1].get("type") != "string"
                or set(items[1].get("enum", [])) != DIAL_VALUES[expected_name]):
            raise ValueError("unapproved dial name or label vocabulary")

    blocker = properties["blockers"]
    if (blocker.get("type") != "array" or blocker.get("minItems") != 0
            or blocker.get("maxItems") != 32 or blocker.get("uniqueItems") is not True):
        raise ValueError("error blocker collection is not closed")
    item = blocker.get("items", {})
    if (item.get("type") != "string" or item.get("minLength") != 1
            or item.get("maxLength") != 150):
        raise ValueError("unreviewed blocker text size/type")
    blocker_regex = item.get("pattern", "")
    if not blocker_regex.startswith("^") or not blocker_regex.endswith("$"):
        raise ValueError("synthetic blocker regex is not anchored")
    for code in BLOCKER_CODES:
        label = (
            f"{SAMPLE_WEEK}:{code}" if code.startswith("TREASURY_")
            or code == "INCOMPLETE_FOUR_SOURCE_SET"
            else f"{SAMPLE_WEEK}:fed_h10_nominal_broad:{code}"
        )
        if re.fullmatch(blocker_regex, label) is None:
            raise ValueError("known no-provider blocker omitted: " + code)
    for identifier in REQUIRED_IDS:
        if re.fullmatch(
            blocker_regex, f"{SAMPLE_WEEK}:{identifier}:MISSING_SYNTHETIC_RECEIPT"
        ) is None:
            raise ValueError("approved invented source ID omitted")
    for invalid in (
        "2026-10-30:INCOMPLETE_FOUR_SOURCE_SET",
        f"{SAMPLE_WEEK}:BUY",
        f"{SAMPLE_WEEK}:https://untrusted.invalid",
        f"{SAMPLE_WEEK}:S&P_500:MISSING_SYNTHETIC_RECEIPT",
        f"{SAMPLE_WEEK}:fed_h10_nominal_broad:INCOMPLETE_FOUR_SOURCE_SET",
    ):
        if re.fullmatch(blocker_regex, invalid):
            raise ValueError("unapproved blocker syntax accepted")

    rules = schema.get("allOf")
    if not isinstance(rules, list) or len(rules) != 2:
        raise ValueError("HOLD/COMPLETE pairing constraints removed")
    by_state = {}
    for rule in rules:
        if_section = rule.get("if", {})
        if if_section.get("required") != ["status"]:
            raise ValueError("conditional does not require status")
        state = if_section.get("properties", {}).get("status", {}).get("const")
        if state in by_state:
            raise ValueError("duplicate conditional status")
        by_state[state] = rule.get("then", {}).get("properties")
    if set(by_state) != STATUSES:
        raise ValueError("status-dependent release boundary incomplete")
    hold, complete = by_state["SYNTHETIC_ONLY_HOLD"], by_state["SYNTHETIC_ONLY_COMPLETE"]
    if (hold != {"dial_labels": {"maxItems": 0}, "blockers": {"minItems": 1}}
            or complete != {"dial_labels": {"minItems": 4, "maxItems": 4},
                           "blockers": {"maxItems": 0}}):
        raise ValueError("HOLD/COMPLETE rule could permit misleading result")


class IndependentMacroSyntheticWireContractTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.schema = json.loads(SCHEMA.read_text(encoding="utf-8"))

    def test_existing_python_dataclass_fields_are_the_only_serialized_fields(self) -> None:
        assert_schema_stays_closed(self.schema)
        expected_fields = {field.name for field in fields(SyntheticContextPanel)}
        for doc in (invented_complete(), invented_hold()):
            with self.subTest(status=doc["status"]):
                self.assertEqual(set(doc), expected_fields)
                self.assertEqual(doc["fixture_marker"], SYNTHETIC_MARKER)
                self.assertEqual(doc["panel_id"], PANEL_ID)
                self.assertTrue(all(doc[name] is False for name in AUTH_FIELDS))
                self.assertNotIn('"score"', json.dumps(doc))
                self.assertNotIn("USD Impact Score v2", json.dumps(doc))
        self.assertEqual(len(invented_complete()["dial_labels"]), 4)
        self.assertEqual(invented_hold()["dial_labels"], [])
        self.assertEqual(invented_hold()["blockers"], [SAMPLE_BLOCKER])

    def test_schema_mutations_that_grant_or_expand_scope_are_rejected(self) -> None:
        for key in AUTH_FIELDS:
            with self.subTest(flag=key):
                mutated = copy.deepcopy(self.schema)
                mutated["properties"][key]["const"] = True
                with self.assertRaises(ValueError):
                    assert_schema_stays_closed(mutated)
        variants = [
            ("allow extra keys", lambda d: d.__setitem__("additionalProperties", True)),
            ("use external URL as ID", lambda d: d.__setitem__("$id", "https://example.org/live.json")),
            ("allow real date", lambda d: d["properties"]["reference_week"].__setitem__("pattern", ".*")),
            ("allow extra dial", lambda d: d["properties"]["dial_labels"].__setitem__("items", {})),
            ("allow BUY", lambda d: d["properties"]["dial_labels"]["prefixItems"][0]["prefixItems"][1]["enum"].append("BUY")),
            ("drop HOLD blockers", lambda d: d["allOf"][0]["then"]["properties"]["blockers"].__setitem__("minItems", 0)),
            ("drop COMPLETE labels", lambda d: d["allOf"][1]["then"]["properties"]["dial_labels"].__setitem__("minItems", 0)),
            ("allow real source URLs", lambda d: d["properties"]["blockers"]["items"].__setitem__("pattern", ".*")),
        ]
        for label, change in variants:
            with self.subTest(change=label):
                mutated = copy.deepcopy(self.schema)
                change(mutated)
                with self.assertRaises(ValueError):
                    assert_schema_stays_closed(mutated)

    def test_canonical_rights_queues_remain_completely_closed(self) -> None:
        panel = json.loads(PANEL_POLICY.read_text(encoding="utf-8"))
        legacy = json.loads(LEGACY_POLICY.read_text(encoding="utf-8"))
        rights = [r for source in panel["source_permissions"].values()
                  for r in source["rights"].values()]
        self.assertEqual(len(rights), 56)
        self.assertTrue(all(item is False for item in rights))
        self.assertEqual(len(panel["external_authorities"]), 14)
        self.assertTrue(all(item is False for item in panel["external_authorities"].values()))
        self.assertEqual(panel["publication_control"]["status"], "HOLD")
        self.assertIs(panel["publication_control"]["public_release_authorized"], False)
        self.assertEqual(legacy["state"], "hold")
        self.assertIsNone(legacy["decision_receipt"])

    def test_document_warns_schema_does_not_validate_authenticity_or_calendar(self) -> None:
        text = DOC.read_text(encoding="utf-8")
        self.assertIn("independent_macro_context_synthetic_preview.schema.json", text)
        self.assertIn("not a public", text.lower())
        self.assertIn("not authenticate", text.lower())
        self.assertIn("Friday", text)
        self.assertIn("rights", text.lower())

    @unittest.skipUnless(
        importlib.util.find_spec("jsonschema") is not None,
        "jsonschema is not part of the pinned standard-library-only test dependency boundary",
    )
    def test_optional_full_draft_202012_validator_with_only_invented_documents(self) -> None:
        # Optional cross-check only: core CI tests above require no new package.
        from jsonschema import Draft202012Validator

        Draft202012Validator.check_schema(self.schema)
        validator = Draft202012Validator(self.schema)
        for doc in (invented_complete(), invented_hold()):
            validator.validate(doc)
        for name in AUTH_FIELDS:
            altered = invented_complete()
            altered[name] = True
            self.assertFalse(validator.is_valid(altered))
            altered[name] = 0
            self.assertFalse(validator.is_valid(altered))
        corrupted = [
            ("extra key", {"source_numeric_price": 123.0}),
            ("real date", {"reference_week": "2026-10-30"}),
            ("fake signal", {"dial_labels": [["dollar_breadth", "BUY"], *invented_complete()["dial_labels"][1:]]}),
            ("complete but no labels", {"dial_labels": []}),
            ("complete with blocker", {"blockers": [SAMPLE_BLOCKER]}),
            ("unverified fixture", {"fixture_marker": "LIVE_PROVIDER_DATA"}),
        ]
        for label, override in corrupted:
            with self.subTest(corrupted=label):
                broken = invented_complete() | override
                self.assertFalse(validator.is_valid(broken))
        hold_without_reason = invented_hold() | {"blockers": []}
        self.assertFalse(validator.is_valid(hold_without_reason))


if __name__ == "__main__":
    unittest.main()
